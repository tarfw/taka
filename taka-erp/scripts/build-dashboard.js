import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const projectRoot = path.resolve(__dirname, '..');
const htmlSourcePath = path.join(projectRoot, 'src', 'ui', 'dashboard.html');
const targetTsPath = path.join(projectRoot, 'src', 'ui', 'dashboard.ts');

if (!fs.existsSync(htmlSourcePath)) {
  console.error(`Source HTML not found at: ${htmlSourcePath}`);
  process.exit(1);
}

const html = fs.readFileSync(htmlSourcePath, 'utf8');
const tsContent = `// Auto-generated by scripts/build-dashboard.js - DO NOT EDIT DIRECTLY
export function renderDashboardHtml(): string {
  return ${JSON.stringify(html)};
}
`;

fs.writeFileSync(targetTsPath, tsContent, 'utf8');
console.log(`[Build] Successfully compiled dashboard.html (${html.length} bytes) to ${targetTsPath}`);
